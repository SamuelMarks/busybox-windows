#!/usr/bin/env python3
"""Declarative manifest of BusyBox applets, configurations, and source files.

This module serves as the single source of truth for:
1. Supported BusyBox applets (name, entry-point ``main`` function, installation
   directory enum, SUID policy, dispatch macro, and config symbol).
2. Enabled boolean configuration symbols (`ENABLED_CONFIGS`).
3. Numeric configuration defaults (`NUMERIC_CONFIG_DEFAULTS`).
4. Required BusyBox C source files (`BUSYBOX_SOURCES`).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final


@dataclass(frozen=True)
class AppletSpec:
    """Specification for a single BusyBox applet entry.

    Attributes:
        name: User-visible applet invocation name (e.g., ``"ash"``, ``"["``).
        main_fn: C entry-point prefix before ``_main`` (e.g., ``"ash"``, ``"test"``).
        dir_enum: BusyBox installation directory enum constant.
        suid_enum: BusyBox SUID handling enum constant.
        macro: Dispatch macro type (``"APPLET"``, ``"APPLET_NOFORK"``,
            ``"APPLET_NOEXEC"``, or ``"APPLET_ODDNAME"``).
        config_symbol: Kconfig symbol controlling the applet (without ``CONFIG_``).
        usage: Short usage summary included in ``usage_compressed.h``.
    """

    name: str
    main_fn: str
    dir_enum: str
    suid_enum: str
    macro: str
    config_symbol: str
    usage: str = "[OPTIONS] [ARGS]..."


